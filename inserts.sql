       CASE (s.i - 1) % 5 WHEN 0 THEN '1A' WHEN 1 THEN '1B' WHEN 2 THEN '1C' WHEN 3 THEN '2A' ELSE '2B' END,
       CASE (s.i - 1) % 5 WHEN 0 THEN 'window' WHEN 1 THEN 'middle' WHEN 2 THEN 'aisle' WHEN 3 THEN 'window' ELSE 'middle' END
